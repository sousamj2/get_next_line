#include <fcntl.h>
#include <stdio.h>
#include "get_next_line.h"

int main(void)
{
	int fd = open("text_1.txt", O_RDONLY);

	char *str;


	do {
		str = get_next_line(fd);		
		printf("New line: [%s]\n", str);
		free(str);
	} while (str != NULL);
	
    return (0);
}
